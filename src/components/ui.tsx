// Peças visuais comuns: botões grandes (≥ 44 px), alto-falante, cabeçalho.
import type { ButtonHTMLAttributes, ReactNode } from 'react';
import { speak } from '../lib/speech';

type Variant = 'primary' | 'secondary' | 'ghost' | 'danger';

const VARIANTS: Record<Variant, string> = {
  primary: 'bg-primary text-primary-ink',
  secondary: 'bg-surface text-ink border border-line',
  ghost: 'text-primary',
  danger: 'bg-danger-soft text-danger border border-danger/40',
};

export function Button({
  variant = 'primary',
  className = '',
  ...props
}: ButtonHTMLAttributes<HTMLButtonElement> & { variant?: Variant }) {
  return (
    <button
      {...props}
      className={`min-h-12 rounded-xl px-4 text-base font-semibold transition active:scale-[0.98] disabled:opacity-40 ${VARIANTS[variant]} ${className}`}
    />
  );
}

export function Speaker({ text, size = 'md', label = 'Ouvir' }: { text: string; size?: 'sm' | 'md' | 'lg'; label?: string }) {
  const dim = size === 'lg' ? 'h-14 w-14' : size === 'sm' ? 'h-10 w-10' : 'h-12 w-12';
  return (
    <button
      type="button"
      aria-label={label}
      onClick={(e) => {
        e.stopPropagation();
        speak(text);
      }}
      className={`${dim} inline-flex shrink-0 items-center justify-center rounded-full bg-primary-soft text-primary active:scale-95`}
    >
      <svg viewBox="0 0 24 24" className="h-1/2 w-1/2" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
        <path d="M11 5 6 9H3v6h3l5 4V5z" />
        <path d="M15.5 8.5a5 5 0 0 1 0 7" />
        <path d="M18.5 5.5a9 9 0 0 1 0 13" />
      </svg>
    </button>
  );
}

export function Screen({ children, className = '' }: { children: ReactNode; className?: string }) {
  return <div className={`safe-pad mx-auto flex min-h-full w-full max-w-md flex-col px-4 ${className}`}>{children}</div>;
}

export function IconButton({ label, onClick, children }: { label: string; onClick: () => void; children: ReactNode }) {
  return (
    <button type="button" aria-label={label} onClick={onClick} className="inline-flex h-11 w-11 items-center justify-center rounded-full text-muted active:bg-surface">
      {children}
    </button>
  );
}

